@dataclass
class TargetResult:
    """Outcome of a token command for one target (a facility, a site, or the e2e token)."""

    kind: str
    target: str
    result: object = None
    error: GlobusIriError = None

    @property
    def ok(self):
        return self.error is None


def _target_label(m):
    return "e2e" if m.kind == "e2e" else (f"{m.name} ({m.facility})" if m.kind == "iri" else m.name)


def _check_kind(kind):
    if kind not in KINDS:
        raise ConfigError(f"unknown token kind '{kind}' (known: {', '.join(KINDS)})")


# ---------------------------------------------------------------------- init (no config needed)
def init(work_dir=None, *, sites=None, force=False):
    """Create WORK_DIR, config/sites.yaml and the example job files.

    sites: optional list (or comma-separated string) of example sites to keep.
    Returns {"work_dir", "source", "written": [paths], "kept": [paths]}.
    """
    root, source = (Path(work_dir).resolve(), "work_dir argument") if work_dir else work_dir_source()
    paths = Paths(root)
    for parent in [paths.root, *paths.root.parents]:
        if (parent / ".git").exists() and not force:
            raise ConfigError(f"WORK_DIR {paths.root} is inside a git work tree ({parent}); tokens must not be "
                              "committed. Set GLOBUSIRI_WORK_DIR elsewhere or pass force=True")
    paths.ensure()
    data = package_data_dir()
    written, kept = [], []
    cfg = paths.default_config
    if cfg.exists() and not force:
        kept.append(cfg)
    else:
        text = (data / "sites.example.yaml").read_text(encoding="utf-8")
        if sites:
            wanted = [s.strip() for s in sites.split(",")] if isinstance(sites, str) else list(sites)
            wanted = [s for s in wanted if s]
            raw = yaml.safe_load(text)
            unknown = [s for s in wanted if s not in raw["sites"]]
            if unknown:
                raise ConfigError(f"sites: unknown in example: {', '.join(unknown)} (known: {', '.join(raw['sites'])})")
            raw["sites"] = {k: v for k, v in raw["sites"].items() if k in wanted}
            text = "# Generated by `globusiri init --sites`; see globusiri/data/sites.example.yaml for comments.\n" + \
                yaml.safe_dump(raw, sort_keys=False)
        cfg.write_text(text, encoding="utf-8")
        written.append(cfg)
    for src in sorted((data / "jobs").glob("*.yaml")):
        dst = paths.jobs_dir / src.name
        if dst.exists() and not force:
            kept.append(dst)
        else:
            shutil.copyfile(src, dst)
            written.append(dst)
    return {"work_dir": paths.root, "source": source, "written": written, "kept": kept}


class GlobusIRI:
    """Entry point of the Python API.

    config:   path to sites.yaml, or a loaded `globusiri.config.Config`. Default: the CLI's
              lookup ($GLOBUSIRI_CONFIG, else <WORK_DIR>/config/sites.yaml).
    work_dir: WORK_DIR override. Default: $GLOBUSIRI_WORK_DIR, else the per-user data dir.

    The config is loaded on first use, so `paths()` works before `init()`.
    """

    def __init__(self, config=None, *, work_dir=None):
        self.paths = Paths(Path(work_dir).resolve()) if work_dir else Paths()
        if config is None or isinstance(config, (str, Path)):
            self._config_path, self._config = config, None
        else:
            self._config_path, self._config = None, config

    @property
    def config(self):
        if self._config is None:
            self._config = load_config(self._config_path, paths=self.paths)
        return self._config

    def site(self, name):
        return self.config.site(name)

    # ------------------------------------------------------------------ paths
    def paths_info(self):
        """Resolved locations as [(what, path, source)]; never fails on a bad config."""
        root, source = work_dir_source()
        if self.paths.root != root:
            source = "work_dir argument"
        cfg_path, cfg_source = self.paths.config_file(self._config_path)
        rows = [
            ("WORK_DIR", self.paths.root, source),
            ("config", cfg_path, cfg_source + ("" if cfg_path.exists() else " (missing: run globusiri init)")),
            ("tokens", self.paths.tokens_dir, "WORK_DIR"),
            ("logs", self.paths.log_file, "WORK_DIR"),
            ("runs", self.paths.runs_dir, "WORK_DIR"),
            ("jobs", self.paths.jobs_dir, "WORK_DIR"),
            ("templates", f"{self.paths.templates_dir}, then {package_data_dir() / 'templates'}", "WORK_DIR, package"),
        ]
        if cfg_path.exists():
            try:
                cfg = self.config
                for fac in cfg.facilities():
                    m = manager("iri", cfg, cfg.sites_for_facility(fac)[0])
                    rows.append((f"iri {fac}", m.access_file, "exists" if m.access_file.exists() else "missing"))
                for site in cfg.sites.values():
                    if site.has_https:
                        m = manager("https", cfg, site)
                        rows.append((f"https {site.name}", m.access_file, "exists" if m.access_file.exists() else "missing"))
                m = manager("e2e", cfg)
                rows.append(("e2e", m.access_file, "exists" if m.access_file.exists() else "missing"))
            except GlobusIriError as exc:
                rows.append(("config error", str(exc), ""))
        return rows

    # ------------------------------------------------------------------ tokens
    def token_managers(self, kind, site=None, *, all_sites=False):
        """Token managers a command acts on. iri: one per facility; https: per site; e2e: one."""
        _check_kind(kind)
        cfg = self.config
        if kind == "e2e":
            return [manager("e2e", cfg)]
        if all_sites:
            sites = list(cfg.sites.values())
        elif site:
            sites = [cfg.site(site)]
        else:
            raise ConfigError("give SITE or --all (all_sites=True)")
        out, seen = [], set()
        for s in sites:
            if kind == "iri":
                if s.facility in seen:
                    continue
                seen.add(s.facility)
            if kind == "https" and not s.has_https:
                if all_sites:
                    continue
                raise ConfigError(f"site {s.name} has no https section")
            out.append(manager(kind, cfg, s))
        return out

    def _each(self, kind, site, all_sites, fn, raise_errors):
        results = []
        for m in self.token_managers(kind, site, all_sites=all_sites):
            r = TargetResult(kind, _target_label(m))
            try:
                r.result = fn(m)
            except GlobusIriError as exc:
                if raise_errors:
                    raise
                r.error = exc
            results.append(r)
        return results

    def login(self, kind, site=None, *, force=False, prompt_login=False, import_file=None):
        """Interactive Globus login (or import a refresh token file). Returns a dict."""
        _check_kind(kind)
        if kind != "e2e" and not site:
            raise ConfigError(f"{kind} login needs a site")
        m = self.token_managers(kind, None if kind == "e2e" else site)[0]
        expires_at = m.login(force=force, prompt_login=prompt_login, import_file=import_file)
        return {"kind": kind, "target": _target_label(m), "refresh_file": m.refresh_file,
                "access_file": m.access_file, "expires_at": expires_at}

    def refresh(self, kind, site=None, *, all_sites=False, min_lifetime=None, upload_to_panda=False,
                validate=None, raise_errors=True):
        """Refresh token -> access token (never prompts). Returns [TargetResult(result=RefreshResult)]."""
        min_life = parse_duration(min_lifetime, self.config.refresh_min_lifetime)
        return self._each(kind, site, all_sites,
                          lambda m: m.refresh(min_lifetime=min_life, upload_to_panda=upload_to_panda, validate=validate),
                          raise_errors)

    def upload_to_panda(self, kind, site=None, *, all_sites=False, raise_errors=True):
        """Access token -> PanDA user secret. Returns [TargetResult(result=secret key)]."""
        def fn(m):
            m.upload_to_panda()
            return m.panda_secret_key
        return self._each(kind, site, all_sites, fn, raise_errors)

    def download_from_panda(self, kind, site=None, *, all_sites=False, raise_errors=True):
        """PanDA user secret -> access token file. Returns [TargetResult(result=token data)]."""
        def fn(m):
            data = m.download_from_panda()
            return {"access_file": m.access_file, "expires_at": data.get("expires_at")}
        return self._each(kind, site, all_sites, fn, raise_errors)

    def token_status(self, kind, site=None, *, all_sites=False, raise_errors=True):
        """Offline: files, permissions, expiry. Returns [TargetResult(result=TokenStatus)]."""
        return self._each(kind, site, all_sites, lambda m: m.status(), raise_errors)

    # ------------------------------------------------------------------ validate
    def validate(self, sites=None, *, kinds=None, job=None, offline=False, write_test=False, panda=False,
                 min_lifetime=None):
        """Validate tokens (live unless offline). Returns [validate.Check].

        job: a job file; then only the tokens that job needs are checked, at its site
        (sites may name at most one site, which overrides the job's site).
        Use `globusiri.validate.failed(checks, strict)` to decide pass/fail.
        """
        kinds = list(kinds or KINDS)
        bad = [k for k in kinds if k not in KINDS]
        if bad:
            raise ConfigError(f"kinds: unknown {', '.join(bad)}")
        if isinstance(sites, str):
            sites = [sites]
        job_obj, site_objs = None, None
        if job:
            if sites and len(sites) > 1:
                raise ConfigError("job validates one site; give at most one site")
            job_obj, _ = resolve_job(self.config, job, site_name=sites[0] if sites else None)
        elif sites:
            site_objs = [self.config.site(s) for s in sites]
        min_life = parse_duration(min_lifetime, self.config.refresh_min_lifetime)
        return validation.validate(self.config, sites=site_objs, kinds=kinds, job=job_obj, offline=offline,
                                   write_test=write_test, panda=panda, min_lifetime=min_life)

    # ------------------------------------------------------------------ jobs
    def resolve_job(self, job, site=None, *, set=None, inputs=None):
        """Merge site job_defaults < job file < overrides. Returns (Job, Site)."""
        overrides = list(set or []) + [f"inputs.{i}" for i in (inputs or [])]
        return resolve_job(self.config, job, site_name=site, overrides=overrides)

    def job_submit(self, job, site=None, *, run_id=None, set=None, inputs=None, dry_run=False, validate=True):
        """Render, upload and submit a job file.

        set: ["key=value", ...] overrides; inputs: ["NAME=LOCAL", ...].
        Returns {"run_id", "job_id", "remote_dir", "stdout_path", "skipped_inputs", "submission"};
        with dry_run: {"run_id", "script", "job_spec", "skipped_inputs"} and nothing is contacted.
        Raises ValidationFailed (with .checks) if the needed tokens fail validation.
        """
        cfg = self.config
        job_obj, site_obj = self.resolve_job(job, site, set=set, inputs=inputs)
        run_id = run_id or jobs.new_run_id()
        if dry_run:
            with tempfile.TemporaryDirectory() as tmp:  # leave no run dir behind
                sub, _ = jobs.prepare(cfg, job_obj, site_obj, run_id, Path(tmp))
                script = Path(sub.script).read_text()
            return {"run_id": run_id, "script": script, "job_spec": sub.job_spec,
                    "skipped_inputs": sub.skipped_inputs}
        if validate:
            checks = validation.validate(cfg, job=job_obj,
                                         kinds=[k for k in job_obj.required_kinds(site_obj) if k != "e2e"])
            if validation.failed(checks):
                exc = ValidationFailed("token validation failed; nothing was uploaded or submitted")
                exc.checks = [c for c in checks if c.status != validation.OK]
                raise exc
        run_dir = cfg.paths.run_dir(run_id)
        state = workflow.RunState(run_dir)
        state.data.update({"run_id": run_id, "site": site_obj.name, "created_at": workflow._now()})
        sub, local_inputs = jobs.prepare(cfg, job_obj, site_obj, run_id, run_dir)
        iri = services.iri_client(cfg, site_obj)
        https = services.https_client(cfg, site_obj) if site_obj.upload_method == "globus_https" else None
        jobs.upload_inputs(cfg, site_obj, sub, local_inputs, iri, https)
        state.set("upload", "done", submission=sub.to_dict(), method=site_obj.upload_method)
        job_id = jobs.launch(site_obj, sub, iri)
        state.set("submit", "done", job_id=job_id)
        return {"run_id": run_id, "job_id": job_id, "remote_dir": sub.remote_dir, "stdout_path": sub.stdout_path,
                "skipped_inputs": sub.skipped_inputs, "submission": sub.to_dict()}

    def _iri(self, site):
        site_obj = self.config.site(site)
        return site_obj, services.iri_client(self.config, site_obj)

    def job_status(self, site, job_id):
        """Returns (state, IRI job report). state is one of jobs.TERMINAL or submitted/running."""
        site_obj, iri = self._iri(site)
        return jobs.status(iri, site_obj, job_id)

    def job_wait(self, site, job_id, *, interval=60, timeout=None, on_update=None, raise_on_failure=False):
        """Poll until the job ends. on_update(state, report) is called on each state change.
        Returns (state, report); with raise_on_failure, a non-finished end raises JobFailed."""
        site_obj, iri = self._iri(site)
        state, report = jobs.wait(iri, site_obj, job_id, interval=interval, timeout=timeout, on_update=on_update)
        if raise_on_failure and state != jobs.FINISHED:
            raise JobFailed(f"job {job_id} ended {state}")
        return state, report

    def job_cancel(self, site, job_id):
        site_obj, iri = self._iri(site)
        return jobs.cancel(iri, site_obj, job_id)

    def job_list(self, site, *, historical=False, limit=None):
        """Returns [{"job_id", "name", "iri_state", "state", "report"}]."""
        _, iri = self._iri(site)
        result = iri.get_jobs(historical=historical, limit=limit)
        items = result if isinstance(result, list) else result.get("jobs") or result.get("items") or []
        out = []
        for j in items:
            st = j.get("status") or {}
            out.append({"job_id": j.get("id"), "name": (j.get("job_spec") or {}).get("name") or j.get("name"),
                        "iri_state": st.get("state"), "state": jobs.map_state(j), "report": j})
        return out

    def job_cleanup(self, site, run_id):
        """Remove a run's remote directory (and log directory) via IRI rm.
        Returns {path: "removed" | "already gone"}."""
        site_obj, iri = self._iri(site)
        return cleanup_mod.cleanup_run(iri, site_obj, run_id)

    # ------------------------------------------------------------------ IRI filesystem
    def _fs(self, site, resource_id):
        site_obj, iri = self._iri(site)
        return site_obj, iri, resource_id or site_obj.work_dir_resource_id

    def fs_ls(self, site, path, *, resource_id=None, show_hidden=False):
        _, iri, rid = self._fs(site, resource_id)
        return iri.ls(path, resource_id=rid, show_hidden=show_hidden)

    def fs_stat(self, site, path, *, resource_id=None):
        _, iri, rid = self._fs(site, resource_id)
        return iri.stat(path, resource_id=rid)

    def fs_mkdir(self, site, path, *, resource_id=None, parents=False):
        _, iri, rid = self._fs(site, resource_id)
        return iri.mkdir(path, resource_id=rid, parents=parents)

    def fs_chmod(self, site, path, mode, *, resource_id=None):
        _, iri, rid = self._fs(site, resource_id)
        return iri.chmod(path, mode, resource_id=rid)

    def fs_rm(self, site, path, *, resource_id=None, force=False):
        """Remove a file or directory. Without force, path must be below the site's
        remote.work_dir, remote.log_dir or e2e.base_path. Returns True if removed,
        False if it was already gone."""
        site_obj, iri, rid = self._fs(site, resource_id)
        path = cleanup_mod.check_under(path, cleanup_mod.site_roots(site_obj), force=force)
        return cleanup_mod.iri_rm(iri, path, resource_id=rid)

    # ------------------------------------------------------------------ HTTPS staging
    def https_stagein(self, site, files, to, *, mkdir=False, executable=None):
        """Upload local files into the HPC directory `to`. Returns the remote paths."""
        site_obj = self.config.site(site)
        https = services.https_client(self.config, site_obj)
        iri = services.iri_client(self.config, site_obj) if (mkdir or executable) else None
        return https_staging.stagein(https, files, to, iri=iri, site=site_obj, mkdir=mkdir, executable=executable)

    def https_stageout(self, site, files, to, *, overwrite=False):
        """Download remote files into local `to`. Returns {remote: local | "skipped"}."""
        site_obj = self.config.site(site)
        https = services.https_client(self.config, site_obj)
        return https_staging.stageout(https, files, to, skip_existing=not overwrite)

    def https_stageout_job_logs(self, site, job_id, to, *, run_id=None, overwrite=False):
        """Download an IRI job's stdout/stderr. Returns {remote: local | "skipped" | "error: ..."}."""
        site_obj, iri = self._iri(site)
        https = services.https_client(self.config, site_obj)
        _, report = jobs.status(iri, site_obj, job_id)
        return https_staging.stageout_job_logs(https, report, site_obj, to, run_id=run_id, skip_existing=not overwrite)

    # ------------------------------------------------------------------ E2E staging
    def _transfer(self):
        return services.transfer(self.config)

    def e2e_plan(self, site, direction, *, pairs=(), manifest=None, rucio=(), endpoint=None):
        """Build (but do not submit) a transfer plan. Returns staging.e2e.Plan."""
        return e2e_staging.plan(self.config, self.config.site(site), direction, manifest=manifest,
                                rucio=rucio or [], pairs=list(pairs or []), endpoint_label=endpoint)

    def _e2e_transfer(self, site, direction, pairs, manifest, rucio, endpoint, sync_level, wait, on_update, label):
        p = self.e2e_plan(site, direction, pairs=pairs, manifest=manifest, rucio=rucio, endpoint=endpoint)
        transfer = self._transfer()
        task_ids = e2e_staging.submit(transfer, self.config, p, label=label, sync_level=sync_level)
        result = {"direction": direction, "src": p.src.label, "dst": p.dst.label, "files": len(p.items),
                  "task_ids": task_ids}
        if wait:
            result["tasks"] = self.e2e_wait(task_ids, on_update=on_update, transfer=transfer)
        return result

    def e2e_stagein(self, site, pairs=(), *, manifest=None, rucio=(), src_endpoint=None, sync_level=None,
                    wait=True, on_update=None, label=None):
        """Storage endpoint -> HPC. pairs: [(SRC, DST)]; rucio: ["SCOPE:NAME"] (only builds the
        Rucio deterministic RSE path; no Rucio lookup). Returns {"task_ids", "files", ...}."""
        return self._e2e_transfer(site, "stagein", pairs, manifest, rucio, src_endpoint, sync_level, wait,
                                  on_update, label)

    def e2e_stageout(self, site, pairs=(), *, manifest=None, rucio=(), dst_endpoint=None, sync_level=None,
                     wait=True, on_update=None, label=None):
        """HPC -> storage endpoint. Same arguments as e2e_stagein."""
        return self._e2e_transfer(site, "stageout", pairs, manifest, rucio, dst_endpoint, sync_level, wait,
                                  on_update, label)

    def e2e_cleanup(self, site, paths=(), *, manifest=None, rucio=(), force=False, dry_run=False, wait=True,
                    on_update=None, label=None):
        """Delete stage-in files on the HPC endpoint (Globus delete task).

        manifest: stage-in manifest (its DST column is deleted); rucio: ["SCOPE:NAME"] under
        e2e.base_path; paths: HPC mount paths. Returns {"endpoint", "items", "task_ids"}
        (no task_ids with dry_run).
        """
        p = e2e_staging.cleanup_plan(self.config.site(site), manifest=manifest, rucio=rucio or [],
                                     paths=list(paths or []), force=force)
        result = {"endpoint": p.endpoint.label, "items": list(p.items)}
        if dry_run:
            return result
        transfer = self._transfer()
        result["task_ids"] = e2e_staging.submit_delete(transfer, self.config, p, label=label)
        if wait:
            result["tasks"] = self.e2e_wait(result["task_ids"], on_update=on_update, transfer=transfer)
        return result

    def e2e_task(self, task_id, *, failures=False):
        """Task info dict; with failures, adds "failures": [...]."""
        transfer = self._transfer()
        info = e2e_staging.task_info(transfer, task_id)
        if failures:
            info["failures"] = e2e_staging.task_failures(transfer, task_id)
        return info

    def e2e_wait(self, task_ids, *, on_update=None, transfer=None):
        """Wait for Globus tasks; raises JobFailed if one fails or e2e.timeout passes."""
        if isinstance(task_ids, str):
            task_ids = [task_ids]
        return e2e_staging.wait(transfer or self._transfer(), task_ids, poll_interval=self.config.e2e.poll_interval,
                                timeout=self.config.e2e.timeout, on_update=on_update)

    def e2e_cancel(self, task_id):
        return dict(e2e_staging.cancel(self._transfer(), task_id))

    # ------------------------------------------------------------------ end-to-end run
    def run(self, job, site=None, *, set=None, run_id=None, stagein_manifest=None, stageout_manifest=None,
            validate=True, wait=True, interval=60, echo=None):
        """validate -> e2e stagein -> upload -> submit -> monitor -> https download ->
        e2e stageout -> cleanup. Returns workflow.RunState (state.data is the state.json content).
        echo(msg) receives progress lines (default: silent)."""
        job_obj, site_obj = resolve_job(self.config, job, site_name=site, overrides=set)
        return workflow.run(self.config, job_obj, site_obj, run_id=run_id, stagein_manifest=stagein_manifest,
                            stageout_manifest=stageout_manifest, no_wait=not wait, do_validate=validate,
                            interval=interval, echo=echo or (lambda *a: None))

    def resume(self, run_id, *, validate=True, wait=True, interval=60, echo=None):
        """Continue a run; steps already done are skipped. Returns workflow.RunState."""
        return workflow.resume(self.config, run_id, no_wait=not wait, do_validate=validate, interval=interval,
                               echo=echo or (lambda *a: None))

    def run_state(self, run_id):
        """The saved state.json of a run, as a dict."""
        return workflow.RunState.load(self.config.paths.run_dir(run_id)).data
