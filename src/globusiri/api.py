"""Python API: every `globusiri` CLI command as a method.

    from globusiri import GlobusIRI

    g = GlobusIRI()                                   # WORK_DIR and config as the CLI finds them
    g.refresh("iri", all_sites=True, min_lifetime="6h")
    sub = g.job_submit("perlmutter_example_job.yaml", set=["resources.n_node=2"])
    state, report = g.job_wait("NERSC_Perlmutter", sub["job_id"])
    g.https_stageout_job_logs("NERSC_Perlmutter", sub["job_id"], to="out/", run_id=sub["run_id"])
    g.job_cleanup("NERSC_Perlmutter", sub["run_id"])

Methods return plain data (dicts, lists, dataclasses) and never print. Errors are raised
as `globusiri.errors.GlobusIriError` subclasses; each has the CLI exit code as `exit_code`.
The CLI (`globusiri.cli`) is a thin layer that parses arguments, calls these methods and
formats the results.
"""

